package br.edu.pos.apiprodutos.config;

import java.sql.Connection;
import java.sql.DatabaseMetaData;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;

public class Database {

    private static final String URL = "jdbc:h2:file:./dados/produtos;AUTO_SERVER=TRUE";
    private static final String USUARIO = "sa";
    private static final String SENHA = "";

    public static Connection conectar() throws SQLException {
        return DriverManager.getConnection(URL, USUARIO, SENHA);
    }

    public static void inicializar() {
        String criarTabela = """
                CREATE TABLE IF NOT EXISTS produtos (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    nome VARCHAR(150) NOT NULL,
                    preco DOUBLE PRECISION NOT NULL,
                    quantidade_estoque INT DEFAULT 0 NOT NULL
                )
                """;

        try (Connection conexao = conectar(); Statement comando = conexao.createStatement()) {
            comando.execute(criarTabela);
            adicionarColunaEstoqueSeNaoExistir(conexao);
            System.out.println("Banco de dados inicializado!");
        } catch (SQLException erro) {
            throw new RuntimeException("Erro ao inicializar banco de dados.", erro);
        }
    }

    /**
     * Migração compatível com bancos criados antes da inclusão do controle de estoque.
     * A consulta ao metadado evita tratar qualquer erro SQL como se a coluna já existisse.
     */
    private static void adicionarColunaEstoqueSeNaoExistir(Connection conexao) throws SQLException {
        DatabaseMetaData metadados = conexao.getMetaData();
        boolean colunaExiste;

        colunaExiste = false;
        try (ResultSet colunas = metadados.getColumns(null, null, null, null)) {
            while (colunas.next()) {
                String tabela = colunas.getString("TABLE_NAME");
                String coluna = colunas.getString("COLUMN_NAME");
                if ("PRODUTOS".equalsIgnoreCase(tabela)
                        && "QUANTIDADE_ESTOQUE".equalsIgnoreCase(coluna)) {
                    colunaExiste = true;
                    break;
                }
            }
        }

        if (!colunaExiste) {
            try (Statement comando = conexao.createStatement()) {
                comando.execute("ALTER TABLE produtos ADD COLUMN quantidade_estoque INT DEFAULT 0 NOT NULL");
                System.out.println("Coluna quantidade_estoque adicionada ao banco de dados.");
            }
        }
    }
}
